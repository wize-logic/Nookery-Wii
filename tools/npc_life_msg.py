#!/usr/bin/env python3
"""Encode src/game/m_npc_life_msg.txt into src/game/m_npc_life_msg.c_inc.

The villager gossip lines (src/game/m_npc_life.c) are messages the game's
message archive does not have. They are written in msg_tool.py's markup and
stored as encoded game text, served under message numbers from
mNL_MSG_BASE (include/m_npc_life.h) by mMsg_LoadMsgData.
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import msg_tool  # noqa: E402

# Order matches the mNL_TOPIC_* (then mTL_LINE_*) and mNpc_LOOKS_* enums; each topic's number of variants per
# personality.
TOPICS = {
    "LIKE": 4,
    "DISLIKE": 4,
    "PAIR_CLOSE": 4,
    "PAIR_FEUD": 4,
    "NEUTRAL": 4,
    "PLAYER_FAN": 2,
    "MOVING_SAD": 2,
    "MOVING_GLAD": 2,
    "NEWS_MADE_UP": 2,
    "NEWS_FELL_OUT": 2,
    "NEWS_NEW_FRIENDS": 2,
    "SELF_MADE_UP": 2,
    "SELF_FELL_OUT": 2,
    "PLAYER_CATCH": 2,
    # Town life (m_town_life.c): what a villager says when talked to in the middle of an activity
    "ACT_SIT": 1,
    "ACT_DRINK": 1,
    "ACT_EXERCISE": 1,
    "ACT_DANCE": 1,
    "ACT_FISH": 1,
    "ACT_DOZE": 1,
    "ACT_FAN": 1,
    "ACT_PRAY": 1,
    "ACT_PHONE": 1,
}
LOOKS = ["NORMAL", "PEPPY", "LAZY", "JOCK", "CRANKY", "SNOOTY"]

MAX_LINE_WIDTH = 28  # characters, with each placeholder at its widest
MAX_PAGE_LINES = 4
PLACEHOLDER_WIDTH = {
    "STR_FREE13": 8,  # villager names are at most 8 characters
    "STR_FREE14": 8,
    "STR_PLAYERNAME": 8,
    "STR_TAIL": 10,  # ANIMAL_CATCHPHRASE_LEN
    "STR_ITEM0": 18,  # an item name (mIN_ITEM_NAME_LEN) with its article
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(ROOT, "src", "game", "m_npc_life_msg.txt")
DEFAULT_OUT = os.path.join(ROOT, "src", "game", "m_npc_life_msg.c_inc")


def parse(path):
    entries = {}
    key = None
    lines = []

    def flush():
        if key is not None:
            entries[key] = "".join(lines).rstrip("\n")

    with open(path, encoding="utf-8") as f:
        for line in f:
            if key is None and (line.startswith("#") or not line.strip()):
                continue
            if line.startswith("@"):
                flush()
                parts = line[1:].split()
                if len(parts) != 3:
                    raise SystemExit(f"bad header: {line.strip()}")
                topic, looks, variant = parts[0], parts[1], int(parts[2])
                if topic not in TOPICS or looks not in LOOKS or not 0 <= variant < TOPICS[topic]:
                    raise SystemExit(f"unknown entry: {line.strip()}")
                key = (topic, looks, variant)
                if key in entries:
                    raise SystemExit(f"duplicate entry: {line.strip()}")
                lines = []
            else:
                lines.append(line)
    flush()
    return entries


def check_layout(key, text):
    problems = []
    if not text.endswith("<<MSGEND>>"):
        problems.append("does not end with <<MSGEND>>")
    for page in text.split("<<MSGCLEAR>>"):
        page = page.replace("<<MSGEND>>", "")
        shown = [l for l in page.split("\n")]
        while shown and not re.sub(r"<<[^>]*>>", "", shown[-1]).strip():
            shown.pop()
        if len(shown) > MAX_PAGE_LINES:
            problems.append(f"page has {len(shown)} lines")
        for l in shown:
            width = 0
            for tag in re.findall(r"<<([A-Z0-9_]+)[^>]*>>", l):
                width += PLACEHOLDER_WIDTH.get(tag, 0)
            width += len(re.sub(r"<<[^>]*>>", "", l))
            if width > MAX_LINE_WIDTH:
                problems.append(f"line too wide ({width}): {l!r}")
    for p in problems:
        print(f"{' '.join(map(str, key))}: {p}", file=sys.stderr)
    return not problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("src", nargs="?", default=DEFAULT_SRC)
    parser.add_argument("out", nargs="?", default=DEFAULT_OUT)
    args = parser.parse_args()

    entries = parse(args.src)
    ok = True
    out = [
        "/* Generated by tools/npc_life_msg.py from m_npc_life_msg.txt. Do not edit. */",
        "",
        f"#define mNL_MSG_TOPIC_NUM {len(TOPICS)}",
        f"#define mNL_MSG_LOOKS_NUM {len(LOOKS)}",
        "",
    ]
    names = []
    sizes = []
    firsts = []
    for topic, variants in TOPICS.items():
        firsts.append(len(names))
        for looks in LOOKS:
            for variant in range(variants):
                key = (topic, looks, variant)
                if key not in entries:
                    print(f"missing entry: {topic} {looks} {variant}", file=sys.stderr)
                    ok = False
                    continue
                text = entries[key]
                ok &= check_layout(key, text)
                data = msg_tool.encode_entry(text)
                name = f"mNL_msg_{topic.lower()}_{looks.lower()}_{variant}"
                names.append(name)
                sizes.append(len(data))
                out.append(f"static const u8 {name}[] = {{")
                for i in range(0, len(data), 16):
                    out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 16]) + ",")
                out.append("};")
                out.append("")
    if not ok:
        raise SystemExit(1)

    out.append(f"#define mNL_MSG_NUM {len(names)}")
    out.append("")
    out.append("/* Each topic's first message, and its variants per personality (messages: topic, personality, variant) */")
    out.append("static const u16 mNL_msg_topic_first[] = { " + ", ".join(map(str, firsts)) + " };")
    out.append("static const u8 mNL_msg_variants[] = { " + ", ".join(map(str, TOPICS.values())) + " };")
    out.append("")
    out.append("static const u8* const mNL_msg_data[] = {")
    out.extend(f"    {n}," for n in names)
    out.append("};")
    out.append("")
    out.append("static const u16 mNL_msg_size[] = {")
    out.extend(f"    sizeof({n})," for n in names)
    out.append("};")
    out.append("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {len(names)} messages ({sum(sizes)} bytes) to {os.path.relpath(args.out, ROOT)}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Encode src/game/m_town_life_barks.txt into src/game/m_town_life_barks.c_inc.

Barks are the short lines villagers say to each other in speech bubbles
(src/game/m_town_life_bubble.c): one line each, in the game's character set,
per topic and personality. {A} and {B} stand for villager names, which the
bubble code fills in (each up to 8 characters); a bark with its names filled in
fits in MAX_WIDTH characters.

Each topic starts with "@TOPIC PERSONALITY"; every following non-empty line is
one bark (a variant). Every topic needs VARIANTS barks for every personality.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import msg_tool  # noqa: E402

# Order matches mTL_BARK_* in include/m_town_life.h
TOPICS = [
    "CHAT",      # small talk in a group
    "LAUGH",     # a reply: laughing, agreeing
    "LIKE",      # about {A}, a friend of the speaker
    "DISLIKE",   # about {A}, a rival of the speaker
    "PAIR",      # about {A} and {B}, news about the two of them
    "NEWS",      # the speaker has news to tell
    "EXERCISE",  # activities, said while doing them
    "SIT",
    "FISH",
    "DANCE",
    "DRINK",
    "DOZE",
    "FAN",
    "PRAY",
    "PHONE",
    "RAIN",      # weather and night
    "SNOW",
    "STARS",
    "PLANTED",   # the speaker planted flowers (Phase 4)
    "VISITOR",   # {A}, a visitor, is in town (Phase 6)
    "GREET",     # to the player passing by
]
LOOKS = ["NORMAL", "PEPPY", "LAZY", "JOCK", "CRANKY", "SNOOTY"]
VARIANTS = 2

MAX_WIDTH = 24
NAME_WIDTH = 8
NAME_CODE = 0x01  # in the encoded barks, NAME_CODE then 0 ({A}) or 1 ({B})

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(ROOT, "src", "game", "m_town_life_barks.txt")
DEFAULT_OUT = os.path.join(ROOT, "src", "game", "m_town_life_barks.c_inc")


def parse(path):
    barks = {}
    key = None
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if line.startswith("#") or not line.strip():
                continue
            if line.startswith("@"):
                parts = line[1:].split()
                if len(parts) != 2 or parts[0] not in TOPICS or parts[1] not in LOOKS:
                    raise SystemExit(f"{path}:{n}: bad header: {line}")
                key = (parts[0], parts[1])
                if key in barks:
                    raise SystemExit(f"{path}:{n}: duplicate: {line}")
                barks[key] = []
            elif key is None:
                raise SystemExit(f"{path}:{n}: bark before any header")
            else:
                barks[key].append((n, line.strip()))
    return barks


def encode(path, n, text):
    out = []
    width = 0
    i = 0
    while i < len(text):
        if text.startswith("{A}", i) or text.startswith("{B}", i):
            out += [NAME_CODE, 0 if text[i + 1] == "A" else 1]
            width += NAME_WIDTH
            i += 3
            continue
        c = text[i]
        if c not in msg_tool.CHAR_MAP or msg_tool.CHAR_MAP.index(c) == NAME_CODE:
            raise SystemExit(f"{path}:{n}: character {c!r} can't be shown")
        out.append(msg_tool.CHAR_MAP.index(c))
        width += 1
        i += 1
    if width > MAX_WIDTH:
        raise SystemExit(f"{path}:{n}: too wide ({width} > {MAX_WIDTH}): {text}")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("src", nargs="?", default=DEFAULT_SRC)
    parser.add_argument("out", nargs="?", default=DEFAULT_OUT)
    args = parser.parse_args()

    barks = parse(args.src)
    out = [
        "/* Generated by tools/town_life_barks.py from m_town_life_barks.txt. Do not edit. */",
        "",
        f"#define mTL_BARK_TOPIC_NUM {len(TOPICS)}",
        f"#define mTL_BARK_LOOKS_NUM {len(LOOKS)}",
        f"#define mTL_BARK_VARIANTS {VARIANTS}",
        f"#define mTL_BARK_NAME_CODE 0x{NAME_CODE:02X}",
        "",
        "/* barks[topic][looks][variant]: length, then the encoded text */",
        "static const u8 mTL_barks[mTL_BARK_TOPIC_NUM][mTL_BARK_LOOKS_NUM][mTL_BARK_VARIANTS][1 + 2 * "
        f"{MAX_WIDTH}] = {{",
    ]
    for topic in TOPICS:
        out.append(f"    {{ /* {topic} */")
        for looks in LOOKS:
            lines = barks.get((topic, looks), [])
            if len(lines) != VARIANTS:
                raise SystemExit(f"{topic} {looks}: {len(lines)} barks, need {VARIANTS}")
            items = []
            for n, text in lines:
                data = encode(args.src, n, text)
                items.append("{ " + ", ".join(str(b) for b in [len(data)] + data) + " }")
            out.append(f"        {{ /* {looks} */ " + ", ".join(items) + " },")
        out.append("    },")
    out.append("};")
    out.append("")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {len(TOPICS) * len(LOOKS) * VARIANTS} barks to {os.path.relpath(args.out, ROOT)}")


if __name__ == "__main__":
    main()
